/**
 * Bundled global data-center dataset.
 *
 * Major operational facilities (hyperscaler regions, large carrier/co-
 * location campuses) with coordinates accurate to ~city level — plenty
 * for a globe layer. Sources: public provider region maps and facility
 * directories (AWS, Azure, Google Cloud, Equinix, Telehouse, Interxion,
 * Digital Realty, OVH, Hetzner and others).
 *
 * Live lookups were considered (Overpass/Wikidata) but both proved
 * unreliable for this category, so the layer ships offline-complete.
 */

export interface BundledDataCenter {
  name: string;
  operator?: string;
  lat: number;
  lon: number;
}

function dc(name: string, operator: string, lat: number, lon: number): BundledDataCenter {
  return { name, operator, lat, lon };
}

